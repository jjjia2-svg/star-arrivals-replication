#!/usr/bin/env python3
r"""tables_p3afar.py — write the two Panel 3 (A_far) LaTeX tables from the numbers ledger.
Input : output/paper/data_numbers_p3afar.json (made by analysis/paper/ledger_p3afar.py)
Output: output/paper/tab_p3_afar.tex      (compact, in Section 4.1)
        output/paper/tab_p3_afar_full.tex (every horizon, Appendix: Full Regression Tables)
No number in either table is typed by hand. Every cell is wrapped in \REV{} (new material in this version).

Port note: this is a verbatim port of thesis_report/scripts/p3_afar_tables.py (2026-08-22 thesis
copy) — every computation and formatting line is unchanged. Only ROOT/L/output paths are re-derived
from analysis.lib.paths.load_paths(). The "% ... GENERATED by / scripts/p3_afar_tables.py ..."
comment lines written INTO the two .tex outputs are kept byte-identical to the thesis originals on
purpose, so the generated tables stay byte-equal to the thesis's tables/tab_p3_afar*.tex (the
equality check that is this port's spec) — they describe the thesis-side generator, not this file.
Ported 2026-08-23 for the star_arrivals_replication repo (M2/T1).
Freeze-wave Task 8 (2026-08-28): the notes' event-cluster count ("with 33 and 31 events") is now
derived from the ledger instead of hard-coded, and the GENERATED-by comment names the 2026-08-28
thesis ledger; the thesis twin scripts/p3_afar_tables.py carries the identical change.
"""
import json, sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))
from analysis.lib.paths import load_paths

P = load_paths()
ROOT = str(P["output"] / "paper")
L = json.load(open(f"{ROOT}/data_numbers_p3afar.json"))
F = [("econ", "Economics"), ("chemistry", "Chemistry"), ("math_stats", "Mathematics \\& Statistics")]
CAP = L["year_cap"]

def num(x, d=3):
    return f"{x:.{d}f}".replace("-", "$-$")
def big(n): return f"{n:,}".replace(",", "{,}")
def pval(p): return "$<$0.001" if p < 0.001 else f"{p:.3f}"
def R(s): return "\\REV{" + s + "}"
# 2026-08-30: the topic rule is now "both share at least one subfield with the star". The former
# median cut survives as the robustness cell, and its per-discipline values are printed there.
rob_cuts = ", ".join(
    f"{L[f]['robustness']['former_main_cut']['cut']:.2f} in {n.lower().replace(chr(92)+'& statistics','')}"
    for f, n in [("econ", "economics"), ("chemistry", "chemistry"), ("math_stats", "mathematics")])

rows = [
    ("Average post-arrival effect (pp per year)", [num(L[f]["ate_pp"]) for f, _ in F]),
    ("\\quad s.e., pair clusters", [f"({num(L[f]['se_pair_pp'])})" for f, _ in F]),
    ("\\quad s.e., event clusters", [f"({num(L[f]['se_event_pp'])})" for f, _ in F]),
    ("95\\% CI, pair clusters", [f"[{num(L[f]['ci95_pair_pp'][0])}, {num(L[f]['ci95_pair_pp'][1])}]" for f, _ in F]),
    ("Joint test ($p$), pair clusters", [pval(L[f]["p_joint_effects_pair"]) for f, _ in F]),
    ("\\quad event clusters", [pval(L[f]["p_joint_effects_event"]) for f, _ in F]),
    ("MIDRULE", None),
    ("Raw rate before arrival (\\% per year)", [num(L[f]["rate_pre_pp"]) for f, _ in F]),
    (f"Raw rate after arrival, to {CAP} (\\% per year)", [num(L[f]["rate_post_obs_pp"]) for f, _ in F]),
    ("MIDRULE", None),
    ("Pairs", [big(L[f]["pairs"]) for f, _ in F]),
    ("First ties", [big(L[f]["first_ties"]) for f, _ in F]),
    ("Events with pairs", [str(L[f]["events_with_pairs"]) for f, _ in F]),
    ("Pair--event--years", [big(L[f]["rows"]) for f, _ in F]),
]
out = []
out.append("% Table: Panel 3 under the same-topic / outside-network definition. GENERATED by")
out.append("% scripts/p3_afar_tables.py from data_numbers_2026-08-28_p3afar.json — do not edit numbers by hand.")
out.append("\\begin{table}[ht]\n\\centering")
out.append("\\caption{" + R("First ties among same-topic incumbents outside the star's network (Panel 3)") + "}")
out.append("\\label{tab:p3afar}\n\\footnotesize\\setlength{\\tabcolsep}{3pt}")
out.append("\\begin{tabular}{@{}l r r r@{}}\n\\toprule")
out.append(" & " + R("Economics") + " & " + R("Chemistry") + " & \\multicolumn{1}{r}{\\shortstack[r]{" + R("Mathematics") + "\\\\ " + R("\\& Statistics") + "}} \\\\\n\\midrule")
for lab, vals in rows:
    if lab == "MIDRULE": out.append("\\midrule"); continue
    out.append(R(lab) + " & " + " & ".join(R(v) for v in vals) + " \\\\")
out.append("\\bottomrule\n\\end{tabular}")
out.append("\\par\\smallskip\n\\begin{minipage}{0.95\\textwidth}\\footnotesize")
out.append(R("\\emph{Notes}: Each column is one estimation of equation~\\eqref{eq:p3} with the estimator of "
             "Section~\\ref{sec:baseline}, on pairs of department-roster incumbents who were outside the star's "
             "two-hop pre-arrival coauthorship network and who both share at least one subfield with the star, "
             "network position and dose fixed one year before arrival. Incumbents who "
             "had published with the star before the arrival, and pairs that had published together before the six-year "
             "pre-arrival window, are excluded. The outcome is an indicator for the first joint publication of the pair; "
             "a paper that also carries the star's name does not count; the pair leaves the sample after its first tie. "
             "The average effect is the switcher-weighted mean of the five post-arrival coefficients, in percentage points "
             "(pp) of the yearly first-tie probability; the joint test is of the five post-arrival coefficients. Standard errors are in parentheses, clustered by pair (the main "
             f"convention of Section~\\ref{{sec:baseline}}) and by event; with {L['chemistry']['events_with_pairs']} and {L['math_stats']['events_with_pairs']} events the event clusters in "
             "chemistry and mathematics are few, and few-cluster standard errors tend to be too small "
             "(Section~\\ref{sec:baseline}). The pre-arrival placebo coefficients are zero by construction in this panel "
             "and are not reported. Raw first-tie rates are the share of pair-years with a first tie, without any "
             "comparison group, over the six pre-arrival years and over the arrival year and the five years after it, "
             f"restricted to calendar years up to {CAP} because later years are incompletely covered by the 26 June 2026 "
             "snapshot. Horizon-by-horizon estimates are in Table~\\ref{tab:p3afar_full}."))
out.append("\\end{minipage}\n\\end{table}")
open(f"{ROOT}/tab_p3_afar.tex", "w").write("\n".join(out) + "\n")

o = []
o.append("% Table: Panel 3 (same-topic / outside-network pairs), every horizon. GENERATED by")
o.append("% scripts/p3_afar_tables.py from data_numbers_2026-08-28_p3afar.json — do not edit numbers by hand.")
o.append("\\begin{table}[ht]\n\\centering")
o.append("\\caption{" + R("Panel 3 horizon by horizon (same-topic incumbents outside the star's network)") + "}")
o.append("\\label{tab:p3afar_full}\n\\small")
o.append("\\begin{tabular}{@{}l r r r r r@{}}\n\\toprule")
o.append(" & ".join(R(h) for h in ["Years since arrival $\\ell$", "Estimate (pp)", "s.e., pair", "s.e., event", "Pair--event--years", "Switchers"]) + " \\\\")
for f, name in F:
    o.append("\\midrule")
    o.append("\\multicolumn{6}{@{}l}{" + R(f"\\emph{{{name}}}: {big(L[f]['pairs'])} pairs, {big(L[f]['first_ties'])} first ties, {L[f]['events_with_pairs']} events") + "} \\\\")
    for h in L[f]["horizons_pp"]:
        o.append(" & ".join(R(v) for v in [str(h['ell']), num(h['est']), f"({num(h['se_pair'])})", f"({num(h['se_event'])})", big(h['n']), big(h['switchers'])]) + " \\\\")
    o.append(" & ".join(R(v) for v in ["Average", num(L[f]['ate_pp']), f"({num(L[f]['se_pair_pp'])})", f"({num(L[f]['se_event_pp'])})", "", ""]) + " \\\\")
o.append("\\bottomrule\n\\end{tabular}")
o.append("\\par\\smallskip\n\\begin{minipage}{0.95\\textwidth}\\footnotesize")
o.append(R("\\emph{Notes}: Coefficients $\\delta_\\ell$ of equation~\\eqref{eq:p3}, in percentage points of the yearly "
           "first-tie probability, with $\\ell=-1$ normalized to zero; $\\ell=0$ is the arrival year. Pair--event--years is the "
           "number of observations entering the comparison at that horizon, and switchers the number of treated pairs entering "
           "it (treated pairs with a not-yet-treated comparison pair in the same calendar year). The average is the "
           "switcher-weighted mean of the five horizons. Pre-arrival placebo coefficients are zero by construction and omitted "
           "(Section~\\ref{sec:baseline}). Sample definition as in Table~\\ref{tab:p3afar}."))
o.append("\\end{minipage}\n\\end{table}")
open(f"{ROOT}/tab_p3_afar_full.tex", "w").write("\n".join(o) + "\n")
print("wrote tab_p3_afar.tex and tab_p3_afar_full.tex")
