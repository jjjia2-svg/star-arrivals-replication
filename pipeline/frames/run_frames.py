def _sha(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def unregistered_scripts() -> list[str]:
    """Ported scripts in this layer that are neither a stage nor declared NOT_RUNNABLE."""
    known = {s.script for s in STAGES.values()} | {a for s in STAGES.values() for a in s.also} \
        | set(NOT_RUNNABLE)
    me = pathlib.Path(__file__).resolve()
    found = sorted(f.relative_to(FRAMES_DIR).as_posix() for f in FRAMES_DIR.rglob("*.py")
                   if f.resolve() != me and "__pycache__" not in f.parts)
    return [f for f in found if f not in known]


def _preimport_units(extra: tuple[str, ...] = ()) -> list[str]:
    """Bind the FWCI and output-rule modules to the REPO's ported copies. See the docstring.

    `extra` names further repo unit modules a stage's ported script imports from the legacy tree
    (cal2026-08-28 T3: the union-frame builder pulls `identity.dose`, `identity.first_pub` and
    `common._redlines` through its own `sys.path.insert` on the legacy units). Same mechanism,
    same origin assertion."""
    for src in UNIT_SRC:
        if not src.is_dir():
            raise PathUnresolved(f"ported unit tree missing: {src}")
        if str(src) not in sys.path:
            sys.path.insert(0, str(src))
    used = []
    modules = ("m5_output.fwci_baseline_build", "m5_output.fwci_raw", "identity.output_rule")
    for module in (modules + tuple(m for m in extra if m not in modules)) if extra else modules:
        loaded = importlib.import_module(module)
        origin = pathlib.Path(getattr(loaded, "__file__", "") or "").resolve()
        if not origin.is_relative_to(REPO / "pipeline" / "units"):
            raise PathUnresolved(
                f"'{module}' resolved to {origin}, not to this repository's ported units. The "
                f"builder would compute its y column with the LEGACY code.")
        used.append(f"{module} <- {origin.relative_to(REPO)}")
    return used


def _stage_root(stage: str) -> pathlib.Path:
    """`<scratch>/<stage>`, judged by the write barrier and cleared.

    One subdirectory PER STAGE, not one scratch root for the layer: four stages share the
    `econ_fnfix_2026-08-15` run directory and two share `p3_topicpair_2026-08-17`, so a single root
    would let one stage's rebuild sit in another's mirror and be compared as if it had just been
    produced. Only the stage's OWN subdirectory is cleared — clearing the whole root would delete a
    sibling stage's output between its run and its comparison, which is exactly the failure this
    split exists to prevent.

    The barrier is still what decides where output may go, and the one rule it applies that does not
    fit here is "an existing non-empty directory is a frozen artifact": after the first stage the
    scratch root is non-empty BY THIS LAUNCHER'S OWN DOING. So the exemption is proved rather than
    assumed — every entry must be a directory named after a declared stage; anything else and the
    root is refused, because then it is not this launcher's scratch tree.
    """
    override = os.environ.get(OUT_ROOT_ENV, "").strip()
    if override or not SCRATCH.exists() or not any(SCRATCH.iterdir()):
        scratch = output_target(SCRATCH, f"frames {stage}")   # judges $SAR_OUT_ROOT itself
    else:
        unknown = sorted(p.name for p in SCRATCH.iterdir() if p.name not in STAGES)
        if unknown or SCRATCH.is_symlink():
            raise PathUnresolved(
                f"refusing to use {SCRATCH} as the frames scratch root: it holds {unknown or 'a '
                'symlink'}, which this launcher did not put there. Empty it, or set "
                f"${OUT_ROOT_ENV} to an absolute path outside the repo.")
        scratch = SCRATCH
    root = scratch / stage
    if root.is_dir() and not root.is_symlink() and root.parent == scratch:
        shutil.rmtree(root)
    root.mkdir(parents=True, exist_ok=True)
    return root


def _link(src: pathlib.Path, dest: pathlib.Path) -> str:
    """Put `src` at `dest` without changing a byte (hard link, copy across filesystems)."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists() or dest.is_symlink():
        dest.unlink()
    how = "hard link"
    try:
        os.link(src, dest)
    except OSError:
        shutil.copyfile(src, dest)
        how = "copy"
    want, got = _sha(src), _sha(dest)
    if want != got:
        raise SystemExit(f"[run_frames] staged file differs from its source: {want} != {got}")
    return f"{how}, sha256 {got}"


def _run_dir_name(script: str) -> str:
    return script.split("/", 1)[0]


def run(stage: str, execute: bool, rest: list[str]) -> int:
    spec = STAGES[stage]
    if spec.gate and not execute:
        print(f"[run_frames] stage '{stage}' is OFF by default. Cost:\n\n  {spec.gate}\n\n"
              f"  Re-run with --execute if you really want it:\n"
              f"      python3 pipeline/frames/run_frames.py {stage} --execute", file=sys.stderr)
        return 2
    ported = FRAMES_DIR / spec.script
    if not ported.is_file():
        print(f"[run_frames] ported script missing: {ported}", file=sys.stderr)
        return 2
    try:
        root = _stage_root(stage)
        v2 = legacy_thesis() / "v2_output"
    except PathUnresolved as exc:
        print(f"[run_frames] {exc}", file=sys.stderr)
        return 2
    run_dir = root / _run_dir_name(spec.script)
    run_dir.mkdir(parents=True, exist_ok=True)
    print(f"[run_frames] {stage}: run directory -> {run_dir}")

    # The anchor the ported preamble walks to. With the default scratch root it resolves to the
    # repo; with `$SAR_OUT_ROOT` set it does not, and that is SAFE HERE but only here: this
    # launcher runs the staged file with `runpy` IN THIS PROCESS, where `pipeline.lib.paths` is
    # already imported, so the preamble's `sys.path.append` is inert and the module the ported code
    # binds is this repository's. Say so rather than leaving the reader to work it out - and prove
    # the claim instead of asserting it.
    anchor = next(p for p in (run_dir / "code" / "x.py").parents if p.name == "frames")
    import pipeline.lib.paths as _resolver                                     # noqa: PLC0415
    origin = pathlib.Path(_resolver.__file__).resolve()
    if not origin.is_relative_to(REPO):
        print(f"[run_frames] pipeline.lib.paths resolved to {origin}, not to this repository. The "
              f"ported builders would resolve their paths with someone else's resolver.",
              file=sys.stderr)
        return 2
    if anchor.parents[1] != REPO:
        print(f"[run_frames] NOTE: the scratch root {anchor} does not sit two levels under the "
              f"repo, so the ported preamble's own repo anchor would be {anchor.parents[1]}. It is "
              f"inert under this launcher (pipeline.lib.paths is already imported, from "
              f"{origin.relative_to(REPO)}), but a staged file run DIRECTLY from there would fail "
              f"to import it.")

    if spec.units or spec.unit_modules:
        for line in _preimport_units(spec.unit_modules):
            print(f"[run_frames] unit module {line}")
    for rel in spec.dirs:
        (run_dir / rel).mkdir(parents=True, exist_ok=True)
    target = run_dir / "code" / ported.name
    print(f"[run_frames] staged {ported.relative_to(REPO)} ({_link(ported, target)})")
    for dest_rel, src_rel in spec.links:
        src = v2 / src_rel
        if not src.is_file():
            print(f"[run_frames] input missing: {src}", file=sys.stderr)
            return 2
        print(f"[run_frames] input {dest_rel} <- v2_output/{src_rel} "
              f"({_link(src, run_dir / dest_rel)})")

    sys.argv = [str(target), *rest]
    os.environ.setdefault("PYTHONHASHSEED", "0")
    os.environ[STAGE_ROOT_ENV] = str(root.resolve())
    for k, v in spec.env:
        os.environ[k] = v
        print(f"[run_frames] environment {k}={v}  (the original run's value; see README.md)")
    here = pathlib.Path.cwd()
    t0 = time.time()
    try:
        if spec.cwd:                              # the recovered producers ran `cd <run dir> && …`
            os.chdir(run_dir)
            print(f"[run_frames] working directory -> {run_dir}")
        with staged_run(target):                  # in-process staged-run marker (T8)
            runpy.run_path(str(target), run_name="__main__")
        for extra in spec.also:
            more = FRAMES_DIR / extra
            dest = run_dir / "code" / more.name
            print(f"[run_frames] staged {more.relative_to(REPO)} ({_link(more, dest)})")
            sys.argv = [str(dest), *rest]
            with staged_run(dest):
                runpy.run_path(str(dest), run_name="__main__")
    except PathUnresolved as exc:
        print(f"[run_frames] {exc}", file=sys.stderr)
        return 2
    except SystemExit as exc:
        if int(exc.code or 0):
            return int(exc.code or 0)
    finally:
        os.chdir(here)
        os.environ.pop(STAGE_ROOT_ENV, None)
        for k, _ in spec.env:
            os.environ.pop(k, None)
    field = next((a for a in rest if a in ("chemistry", "math_stats")), "")
    print(f"[run_frames] {stage} finished in {time.time() - t0:.1f} s; outputs:")
    for rel in spec.outputs:
        f = run_dir / rel.format(field=field)
        print(f"    {'OK  ' if f.is_file() else 'MISSING'} {f}"
              + (f"  ({f.stat().st_size:,} B, sha256 {_sha(f)})" if f.is_file() else ""))
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Run a ported frame builder in a staged run directory.")
    ap.add_argument("stage", nargs="?", choices=sorted(STAGES), help="which stage to run")
    ap.add_argument("--execute", action="store_true",
                    help="required by the stages that need the data disk")
    ap.add_argument("--list", action="store_true", help="list the stages, their cost and outputs")
    ap.add_argument("rest", nargs=argparse.REMAINDER, help="arguments passed to the ported script")
    argv = list(sys.argv[1:] if argv is None else argv)
    execute = "--execute" in argv
    argv = [a for a in argv if a != "--execute"]
    args = ap.parse_args(argv)
    args.execute = execute

    if args.list or not args.stage:
        print(f"frame stages (set ${OUT_ROOT_ENV} to move the scratch root):\n")
        for name, spec in STAGES.items():
            print(f"  {name:9s} {spec.script}" + ("  [RECOVERED]" if spec.recovered else ""))
            print("            " + ("** OFF BY DEFAULT - needs --execute: " + spec.gate
                                    if spec.gate else "runs by default")
                  + f"  [measured: {spec.minutes} min]")
            for rel in spec.frames:
                print(f"            -> data/frames/{rel}")
            if not spec.frames:
                print("            -> ** NO FROZEN FRAME REGISTERED")
        print("\n  ported scripts with no runnable stage (read and judged, not forgotten):")
        for script, why in NOT_RUNNABLE.items():
            print(f"    {script}\n        {why[:110]}...")
        if unregistered_scripts():
            print(f"\n  !! ported script(s) neither staged nor declared: {unregistered_scripts()}")
        return 0 if args.stage else 1
    return run(args.stage, args.execute, [a for a in args.rest if a != "--"])


if __name__ == "__main__":
    raise SystemExit(main())
