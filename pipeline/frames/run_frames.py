#!/usr/bin/env python3
"""The entry point for the ported frame builders — repo-authored, not part of the port.

This is the layer the whole analysis layer reads: the 21 frozen files in `data/frames/`. Which
builder wrote which one, and how that was settled, is in `pipeline/frames/README.md`.

Why a launcher, and why this shape. Two problems, both consequences of how the legacy builders were
written, and neither solvable inside the port under M3's verbatim rule:

1. `01_merge_inputs.py` and `50_leftbehind_build.py` compute their output directory from their own
   file (`BASE = dirname(dirname(abspath(__file__)))`) — a line holding no absolute path, therefore
   untouchable. So this launcher moves the FILE: it materialises a run directory under the repo's
   git-ignored `output/` tree, hard-links the ported script into `<run dir>/code/` (byte-identity
   asserted, not assumed), links the inputs the script reads relative to `BASE`, and runs THAT.
2. The other four builders were machine-generated by `econ_fnfix_2026-08-15/code/02_clone_chain.py`,
   which expanded every path into a full absolute literal. Those ARE path hunks, but each script has
   three to five separate WRITE destinations, and `output_target()`'s `$SAR_OUT_ROOT` redirect is
   single-use: the second write fails on a root the first write just filled. They go through
   `staged_run_dir()` instead — the same staging mirror, addressed per file (see pipeline/lib/paths).

Both mechanisms need the mirror to exist first, which is this file's job, and neither can fall back
to the legacy location: without `$SAR_STAGE_ROOT` the resolver raises.

A third hazard is specific to this layer. `04_rebuild_y.py` and `20_rebuild_y_gold.py` reach the FWCI
and output-rule machinery with `sys.path.insert(0, f"{ROOT}/multiplex_pipeline/units/…")`, and `ROOT`
resolves to the read-only legacy tree, because that is where the frames' other inputs still live.
Left alone, a repo run would compute its y column with the LEGACY units. So this launcher pre-imports
this repository's ported copies under those exact module names before the script starts: `sys.modules`
already holds them, the insert becomes inert, and the run record prints each module's `__file__`. The
copies are byte-identical (`tests/test_verbatim_pipeline.py` proves it), so this changes which file is
read, never what it says — the arrangement `pipeline/stars/run_stars.py` uses for the ranking machine.

    python3 pipeline/frames/run_frames.py --list
    python3 pipeline/frames/run_frames.py afar               # ~5 s, no data disk
    python3 pipeline/frames/run_frames.py split              # < 1 s, no data disk
    python3 pipeline/frames/run_frames.py p1-gold --execute -- --field chemistry

`$SAR_OUT_ROOT` moves the scratch root, is itself judged by the write barrier, and is single-use.
Without it the scratch root is `<repo>/output/frames`, and each stage gets its own subdirectory
there, which this launcher CLEARS before staging.
"""
