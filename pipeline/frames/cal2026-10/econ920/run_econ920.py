def collections_counter(rel: pathlib.Path) -> dict:
    import collections                                                   # noqa: PLC0415
    return dict(collections.Counter(r["channel"] for r in L.read_rows(rel)))


def _p1_summary(p: pathlib.Path) -> dict:
    j = json.loads(p.read_text("utf-8"))
    out = {"rows_raw": j.get("rows_raw"), "rows_kept": j.get("rows_kept")}
    for name, ch_ in (j.get("channels") or {}).items():
        out[name] = {k: ch_.get(k) for k in ("status", "obs", "rels", "persons", "events", "ate", "se",
                                             "p_joint_effects", "p_joint_placebo")}
    return out


def _p2_summary(p: pathlib.Path) -> dict:
    j = json.loads(p.read_text("utf-8"))
    return {k: j.get(k) for k in ("status", "rows", "rels", "persons", "events", "first_ties", "ate", "se",
                                  "p_joint_effects", "p_joint_placebo")}


