def chain_from_union(root: pathlib.Path, tag: str, shadow_root: pathlib.Path, sh: L.fs08.Shadow,
                     with_split: bool = True) -> dict:
    """p1-econ -> (split) -> p2-econ -> make_slim on a shadow whose union outputs are in place.
    A p1-econ failure (the script's own gate) is recorded, not raised; the later stages run."""
    rec: dict = {}
    try:
        st = L.run_stage("p1-econ", root / f"{tag}_p1", execute=True, shadow=shadow_root)
        rec["p1_econ"] = {"run_dir": str(st["run_dir"]), "secs": st["secs"], "status": "OK"}
        sh.install(f"{L.ECON}/data/analysis_frame_econ920_unified_fullsnap_2026-08-13.csv",
                   st["run_dir"] / "data/analysis_frame_econ920_unified_fullsnap_2026-08-13.csv",
                   f"cal-stage:p1-econ ({tag})")
        rec["p1_frame"] = sh.path(f"{L.ECON}/data/analysis_frame_econ920_unified_fullsnap_2026-08-13.csv")
        p1_dir = st["run_dir"]
    except RuntimeError as exc:
        p1_dir = next((root / f"{tag}_p1" / "frames" / "p1-econ").glob("*"), None)
        rec["p1_econ"] = {"status": "FAILED", "error": str(exc)[-3000:], "run_dir": str(p1_dir)}
        rec["p1_frame"] = None
    if p1_dir is not None and (p1_dir / "data/g_econ_rebuild.json").is_file():
        g = json.loads((p1_dir / "data/g_econ_rebuild.json").read_text("utf-8"))
        rec["p1_econ"]["g_econ_rebuild"] = {
            "PASS": g.get("PASS"),
            "C_PC_structural_anchor": g.get("C_PC_structural_anchor"),
            "C_PC_fnfix_newevent_rows": {k: v for k, v in g.get("C_PC_fnfix_newevent_rows", {}).items()
                                         if k != "examples_missing"},
            "old_value_reproduction_anchor": {k: v for k, v in g.get("old_value_reproduction_anchor", {}).items()
                                              if not k.startswith("examples")},
            "variants": g.get("variants"), "path": str(p1_dir / "data/g_econ_rebuild.json")}
        rec["p1_econ"]["unified_frame_written"] = str(p1_dir / "data/analysis_frame_econ920_unified_fullsnap_2026-08-13.csv")
    if with_split and rec["p1_frame"] is not None:
        st = L.run_stage("split", root / f"{tag}_split", shadow=shadow_root)
        rec["split"] = {"run_dir": str(st["run_dir"]), "secs": st["secs"]}
        rec["old79"] = st["run_dir"] / "data/analysis_frame_econ_fnfix_old79.csv"
        rec["new37"] = st["run_dir"] / "data/analysis_frame_econ_fnfix_new38.csv"
    st = L.run_stage("p2-econ", root / f"{tag}_p2", execute=True, shadow=shadow_root)
    rec["p2_econ"] = {"run_dir": str(st["run_dir"]), "secs": st["secs"]}
    for name in ("becoming_unified.csv", "pairs_unified.csv", "panels23_report.json"):
        sh.install(f"{L.ECON}/data/{name}", st["run_dir"] / f"data/{name}", f"cal-stage:p2-econ ({tag})")
    rec["p2_frame"] = sh.path(f"{L.ECON}/data/becoming_unified.csv")
    rec["pairs"] = sh.path(f"{L.ECON}/data/pairs_unified.csv")
    rec["panels23_report"] = sh.path(f"{L.ECON}/data/panels23_report.json")
    rec["slim"] = L.run_make_slim("econ", rec["pairs"], root / f"{tag}_slim")
    return rec


def control_c2(root: pathlib.Path, v2: pathlib.Path) -> None:
    rep = REPORT.setdefault("controls", {}).setdefault("c2", {})
    shadow_root = pathlib.Path(REPORT["_c1b_shadow"]["root"])
    sh = L.fs08.Shadow(shadow_root / "v2_output")
    sh.entries = list(REPORT["_c1b_shadow"]["entries"])
    ch = chain_from_union(root, "c2", shadow_root, sh)
    rep["chain"] = {k: (str(v) if isinstance(v, pathlib.Path) else v) for k, v in ch.items()
                    if k not in ("slim",)}
    rep["chain"]["slim"] = {k: (str(v) if isinstance(v, pathlib.Path) else v) for k, v in ch["slim"].items()}
    if ch["p1_frame"] is None:
        set_verdict("c2", False, "p1-econ failed on the 08-28 inputs")
        return
    cmp = {}
    for name, produced in (("p1_frame_econ.csv", ch["p1_frame"]), ("p1_frame_econ_old79.csv", ch["old79"]),
                           ("p1_frame_econ_new37.csv", ch["new37"]), ("p2_becoming_econ.csv", ch["p2_frame"])):
        cmp[name] = {"sha256": sha(produced), "frozen_sha256": sha(L.FRAMES / name),
                     "verdict": "BYTE_EQUAL" if sha(produced) == sha(L.FRAMES / name) else "NOT_EQUAL"}
        if cmp[name]["verdict"] != "BYTE_EQUAL" and name != "p2_becoming_econ.csv":
            cmp[name]["characterised"] = L.characterise_frame(L.FRAMES / name, produced)
    cmp["p3_slim_econ.parquet"] = L.content_verdict(ch["slim"]["noev"], L.FRAMES / "p3_slim_econ.parquet",
                                                    accept=[("grp", "BIGINT", "INTEGER")])
    cmp["p3_slim_ev_econ.parquet"] = L.content_verdict(ch["slim"]["ev"], L.FRAMES / "p3_slim_ev_econ.parquet",
                                                       accept=[("grp", "BIGINT", "INTEGER")])
    cmp["pairs_unified_sha256"] = sha(ch["pairs"])
    rep["frames"] = cmp
    frames_ok = all(v["verdict"] == "BYTE_EQUAL" for k, v in cmp.items() if k.endswith(".csv")) and \
        cmp["p3_slim_econ.parquet"]["equal"] and cmp["p3_slim_ev_econ.parquet"]["equal"]
    log(f"c2 frames: { {k: (v.get('verdict') or v.get('equal')) for k, v in cmp.items() if isinstance(v, dict)} }")
    cells = {}
    for label, driver, frame in (("P1_econ_fnfix", "run_p1.R", ch["p1_frame"]),
                                 ("P1_econ_fnfix_old79", "run_p1.R", ch["old79"]),
                                 ("P1_econ_fnfix_new37", "run_p1.R", ch["new37"]),
                                 ("P2_econ_fnfix", "run_p2.R", ch["p2_frame"])):
        out = L.run_r_cell(driver, label, frame, root / "c2_cells")
        cells[label] = L.compare_cells(out, L.EXPECTED / f"{label}.json")
        log(f"c2 cell {label}: {cells[label]['verdict']}")
    rep["cells"] = cells
    cells_ok = all(c["verdict"] == "EQUAL" for c in cells.values())
    set_verdict("c2", frames_ok and cells_ok,
                "" if frames_ok and cells_ok else f"frames_ok={frames_ok} cells_ok={cells_ok}")


