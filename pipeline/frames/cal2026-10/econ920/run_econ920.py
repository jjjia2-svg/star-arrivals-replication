OVERRIDE_RULING = ("Author ruling pending at export time (2026-09-23): the union rung's G-DOSE gate on this draw fails by "
                   "sample composition alone — every failing drawn relation is a residual the frozen 08-15 rows "
                   "carry (measured over the whole population, gdose phase); the gate decides only whether the "
                   "clone writes its file and changes no row. Products built under this override are PROVISIONAL "
                   "until the author signs the ruling; nothing canonical (data/frames, analysis/expected) is touched.")


def override_is_justified(prediction: dict, res: dict) -> tuple[bool, dict]:
    """The evidence gate for the G-DOSE override. Every condition must hold, and the record says
    which did not."""
    pop = REPORT.get("measurements", {}).get("gdose_population")
    resid = residuals()
    rep = res.get("report", {})
    gd = rep.get("G_DOSE", {})
    failing = [w for w in res.get("drawn_residuals_gt_1e-9", []) if w["abs_diff"] > 0.01]
    matched = [w for w in failing if abs(resid.get((w["pid"], w["event_id"]), -1.0) - w["abs_diff"]) < 1e-12]
    other_criteria = (rep.get("G_ROW", {}).get("mismatches") == 0 and rep.get("G_SUM", {}).get("ok") is True)
    gdose_only = (gd.get("share_exact_1e-9") is not None
                  and (gd["share_exact_1e-9"] < 0.90 or (gd.get("max_abs_diff") or 0) > 0.01))
    conds = {
        "population_measured": pop is not None,
        "draw_predicted_FAIL": prediction.get("predicted_gate") == "FAIL",
        "prediction_matches_run": (gd.get("max_abs_diff") == prediction.get("predicted_max_abs_diff")
                                   and gd.get("share_exact_1e-9") == prediction.get("predicted_share_exact_1e-9")),
        "every_failing_relation_is_a_frozen_population_residual": bool(failing) and len(matched) == len(failing),
        "failure_is_gdose_only": gdose_only,
        "G_ROW_zero_mismatches_and_G_SUM_ok": other_criteria,
        "gate_was_intercepted_exactly_once": res.get("gate_overridden") is True,
    }
    rec = {"conditions": conds, "failing_drawn_relations": failing,
           "population": None if pop is None else {k: pop[k] for k in ("n", "share_exact_1e-9", "max_abs_diff",
                                                                          "n_gt_0.01", "n_gt_0.05")},
           "frozen_0813_draw": None if pop is None else pop.get("frozen_0813_draw"),
           "this_draw": {k: gd.get(k) for k in ("n", "missing_side", "max_abs_diff", "share_exact_1e-9")},
           "ruling": OVERRIDE_RULING}
    return all(conds.values()), rec


