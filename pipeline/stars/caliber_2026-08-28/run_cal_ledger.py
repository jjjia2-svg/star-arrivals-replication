#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""caliber_2026-08-28/run_cal_ledger.py — Task-6 driver: the caliber Panel-3 (A_far) ledger.

Repo-authored launcher (declared in `pipeline.lib.paths.LAUNCHERS`). It runs the EXISTING paper
generator `analysis/paper/ledger_p3afar.py` — in place, in this process, via `runpy`, with its
`load_paths()` pointed at the caliber universe — so the author reads the SAME quantities the
thesis quotes, derived by the SAME computation lines, from the cal artifacts. The generator is
not copied and not edited; the only thing that changes is where `load_paths()` says things are:

    frames    -> a scratch shadow holding the cal A_far panels + counts table (sha-verified
                 against data/cal2026-08-28/MANIFEST.sha256 before staging) plus a HEADER-ONLY
                 speed-bracket table: the speed_bracket cap cells have NO builder anywhere
                 (pipeline/NOT_REPRODUCIBLE.md entry 9), so no cal speed bracket can exist and
                 the ledger's speed_bracket block is honestly ABSENT from the cal ledger.
    expected  -> data/cal2026-08-28/estimates/ (the cal estimate JSONs, T4)
    legacy_v2_output, repo_root -> empty scratch dirs, so neither the legacy cross-check nor
                 the frozen no-effect simulations (data/paper_inputs/NULL_*.json — OLD-panel
                 artifacts with no cal counterpart: B0_null_test.R is not in this repository)
                 can leak old-caliber numbers into the cal ledger.

    export SAR_OUT_ROOT=/private/tmp/<empty dir>       # scratch, NEVER under ~/Documents
    python3 "pipeline/stars/caliber_2026-08-28/run_cal_ledger.py" --execute

Phases:
  V  verify — every input (3 A_far panels, counts table, 3 estimate JSONs) hashed against the
     cal MANIFEST: the ledger must derive from the FROZEN cal artifacts, not whatever is on disk.
  R  run — the generator, TWICE (separate scratch universes, $SOURCE_DATE_EPOCH=0 so the PDF is
     byte-stable): the two JSONs and the two figures must be byte-identical (determinism).
  F  freeze — data/cal2026-08-28/data_numbers_cal_p3afar.json (the produced ledger plus ONE
     added top-level key, `_cal_note`, declaring the true cal provenance — the generator's own
     `_source_note` text describes the frozen universe and is kept verbatim beneath it),
     fig_p3_afar_cal.pdf, ledger_run_report_2026-08-28.json; cal MANIFEST regenerated with a
     pure-addition assertion. Any STOP freezes nothing.
"""
from __future__ import annotations

import argparse
import csv
import datetime
import hashlib
import json
import os
import pathlib
import runpy
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
if str(REPO) not in sys.path:
    sys.path.append(str(REPO))

from pipeline.lib.paths import OUT_ROOT_ENV, PathUnresolved, staged_run   # noqa: E402
import analysis.lib.paths as _apaths                                      # noqa: E402

CAL_DIR = REPO / "data" / "cal2026-08-28"
FRAMES = CAL_DIR / "frames"
EST = CAL_DIR / "estimates"
GENERATOR = REPO / "analysis" / "paper" / "ledger_p3afar.py"
LED_OUT = CAL_DIR / "data_numbers_cal_p3afar.json"
FIG_OUT = CAL_DIR / "fig_p3_afar_cal.pdf"
REP_OUT = CAL_DIR / "ledger_run_report_2026-08-28.json"

FIELDS = ("econ", "chemistry", "math_stats")
#: the frozen speed-bracket schema (data/frames/p3_afar_speed_bracket.csv header) — staged
#: header-only so the generator reads ZERO speed rows and omits the block.
SPEED_HEADER = "field,cell,slope_pct,h_post_per1000,cf_trend_per1000,cf_flat_per1000,ratio_trend,ratio_flat"

#: every input the generator reads, all of which must sit in the cal MANIFEST.
INPUTS: tuple[str, ...] = tuple(
    [f"data/cal2026-08-28/frames/p3_afar_{f}.parquet" for f in FIELDS]
    + ["data/cal2026-08-28/frames/p3_afar_counts.csv"]
    + [f"data/cal2026-08-28/estimates/P3lb_{f}_A_far.json" for f in FIELDS])

CAL_NOTE = (
    "CAL 2026-08-28 ledger: generated by pipeline/stars/caliber_2026-08-28/run_cal_ledger.py, "
    "which runs the unedited analysis/paper/ledger_p3afar.py with load_paths() pointed at the "
    "caliber universe — estimates from data/cal2026-08-28/estimates/P3lb_{field}_A_far.json, "
    "raw rates recomputed from data/cal2026-08-28/frames/p3_afar_{field}.parquet, topic cut "
    "from data/cal2026-08-28/frames/p3_afar_counts.csv (all sha-verified against "
    "data/cal2026-08-28/MANIFEST.sha256 before the run). speed_bracket is ABSENT: its "
    "pairs_slim_cap_* inputs have no builder anywhere (pipeline/NOT_REPRODUCIBLE.md entry 9), "
    "so no caliber counterpart exists. null_simulation is ABSENT: B0_null_test.R is not in "
    "this repository, so no caliber no-effect simulation exists. The _source_note below is the "
    "generator's own text and describes the FROZEN universe it normally runs in; it is kept "
    "verbatim because the computation lines it documents are exactly the ones that ran here.")

STOPS: list[str] = []
REPORT: dict = {"task": "T6 caliber p3afar ledger (cal2026-08-28)"}


def log(msg: str) -> None:
    print(f"[run_cal_ledger] {msg}", flush=True)


def stop(msg: str) -> None:
    STOPS.append(msg)
    print(f"\n*** STOP: {msg}", flush=True)


def sha(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def cal_manifest() -> dict[str, str]:
    out = {}
    for line in (CAL_DIR / "MANIFEST.sha256").read_text(encoding="utf-8").splitlines():
        if line.strip():
            h, rel = line.split("  ", 1)
            out[rel] = h
    return out


# ---------------------------------------------------------------------------------------------
# phase R — one generator run in a scratch universe
# ---------------------------------------------------------------------------------------------

def run_once(universe: pathlib.Path) -> dict:
    """Stage the cal universe under `universe`, run the generator, return paths + shas."""
    frames = universe / "frames"
    legacy = universe / "legacy_empty"
    rooted = universe / "repo_root_empty"      # so <repo_root>/data/paper_inputs is empty
    outdir = universe / "output"
    for d in (frames, legacy, rooted, outdir):
        d.mkdir(parents=True)
    for f in FIELDS:
        (frames / f"p3_afar_{f}.parquet").hardlink_to(FRAMES / f"p3_afar_{f}.parquet")
    (frames / "p3_afar_counts.csv").hardlink_to(FRAMES / "p3_afar_counts.csv")
    (frames / "p3_afar_speed_bracket.csv").write_text(SPEED_HEADER + "\n", encoding="utf-8")

    P = {"legacy_v2_output": legacy, "frames": frames, "expected": EST,
         "output": outdir, "repo_root": rooted}
    orig = _apaths.load_paths
    _apaths.load_paths = lambda config_file_path=None: dict(P)
    os.environ["SOURCE_DATE_EPOCH"] = "0"      # byte-stable matplotlib PDF metadata
    try:
        with staged_run(GENERATOR):
            runpy.run_path(str(GENERATOR))
    finally:
        _apaths.load_paths = orig
    led_p = outdir / "paper" / "data_numbers_p3afar.json"
    fig_p = outdir / "paper" / "fig_p3_afar.pdf"
    if not led_p.is_file() or not fig_p.is_file():
        stop(f"generator produced no ledger/figure under {outdir}")
        return {}
    return {"led": led_p, "fig": fig_p, "led_sha": sha(led_p), "fig_sha": sha(fig_p)}


def check_absences(led: dict) -> None:
    for f in FIELDS:
        if "speed_bracket" in led[f]:
            stop(f"{f}: a speed_bracket block appeared — no cal speed bracket exists; "
                 f"the staging leaked the frozen table")
        if "null_simulation" in led[f]:
            stop(f"{f}: a null_simulation block appeared — no cal no-effect simulation "
                 f"exists; the staging leaked data/paper_inputs")


# ---------------------------------------------------------------------------------------------
# driver
# ---------------------------------------------------------------------------------------------

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--execute", action="store_true", help="required")
    ap.add_argument("--refreeze", action="store_true",
                    help="allow replacing an existing frozen cal ledger")
    args = ap.parse_args(argv)
    if not args.execute:
        print("This derives the caliber p3afar ledger from the frozen cal artifacts. "
              "Re-run with --execute.", file=sys.stderr)
        return 2
    out_root = os.environ.get(OUT_ROOT_ENV, "").strip()
    if not out_root:
        raise PathUnresolved(f"set ${OUT_ROOT_ENV} to an empty absolute directory under /private/tmp")
    root = pathlib.Path(out_root)
    if not root.is_dir() or any(root.iterdir()):
        raise PathUnresolved(f"${OUT_ROOT_ENV} must be an existing EMPTY directory: {root}")
    if LED_OUT.exists() and not args.refreeze:
        raise PathUnresolved(f"{LED_OUT} already exists — pass --refreeze to replace it")

    REPORT.update({
        "generated": datetime.datetime.now().isoformat(timespec="seconds"),
        "authority": "the author's decision record of 2026-08-28 (private archive)",
        "generator": "analysis/paper/ledger_p3afar.py",
        "generator_sha256": sha(GENERATOR),
    })

    # ---- V: the inputs must be the FROZEN cal artifacts --------------------------------------
    man = cal_manifest()
    hashes = {}
    for rel in INPUTS:
        got = sha(REPO / rel)
        if man.get(rel) != got:
            stop(f"{rel}: on-disk sha {got[:12]}… != cal MANIFEST {man.get(rel, '?')[:12]}…")
        hashes[rel] = got
    REPORT["input_hashes"] = hashes
    if STOPS:
        return finish(root, ok=False)
    log(f"phase V: {len(hashes)} inputs hash-verified against the cal MANIFEST")

    # ---- R: the generator, twice ------------------------------------------------------------
    r1 = run_once(root / "run1")
    r2 = run_once(root / "run2") if r1 else {}
    if STOPS:
        return finish(root, ok=False)
    REPORT["determinism"] = {
        "led": "EQUAL" if r1["led_sha"] == r2["led_sha"] else "DIFF",
        "fig": "EQUAL" if r1["fig_sha"] == r2["fig_sha"] else "DIFF",
        "compare": "EQUAL" if (r1["led_sha"], r1["fig_sha"]) == (r2["led_sha"], r2["fig_sha"])
        else "DIFF",
        "run1": {"led_sha": r1["led_sha"], "fig_sha": r1["fig_sha"]},
        "run2": {"led_sha": r2["led_sha"], "fig_sha": r2["fig_sha"]}}
    if REPORT["determinism"]["compare"] != "EQUAL":
        stop("the two generator runs differ byte-wise — determinism broken")
    led = json.loads(r1["led"].read_text(encoding="utf-8"))
    check_absences(led)
    # the ledger's own derivation re-checked against the estimate JSONs it read (belt+braces;
    # tests/test_cal_ledger_2026_08_28.py re-derives ALL quantities independently)
    for f in FIELDS:
        j = json.loads((EST / f"P3lb_{f}_A_far.json").read_text(encoding="utf-8"))
        if led[f]["ate_pp"] != round(100 * j["pair_cluster"]["ate"], 3) \
                or led[f]["events_with_pairs"] != j["events"] or led[f]["pairs"] != j["grps"]:
            stop(f"{f}: ledger quantities do not equal the cal estimate JSON")
    with open(FRAMES / "p3_afar_counts.csv", encoding="utf-8") as fh:
        cuts = {r["field"]: float(r["cut"]) for r in csv.DictReader(fh) if r["cell"] == "A_far"}
    for f in FIELDS:
        if led[f]["topic_cut_median_positive_dose"] != cuts[f]:
            stop(f"{f}: ledger topic cut != cal counts table")
    if STOPS:
        return finish(root, ok=False)
    log("phase R: two runs byte-EQUAL; absences verified; estimate/cut identities hold")

    # ---- F: freeze ---------------------------------------------------------------------------
    man_before = cal_manifest()
    frozen = {"_cal_note": CAL_NOTE, **led}
    LED_OUT.write_text(json.dumps(frozen, indent=1, ensure_ascii=False), encoding="utf-8")
    FIG_OUT.write_bytes(r1["fig"].read_bytes())
    for f in FIELDS:
        d = led[f]
        REPORT.setdefault("headline", {})[f] = {
            "ate_pp": d["ate_pp"], "se_pair_pp": d["se_pair_pp"],
            "p_joint_effects_pair": d["p_joint_effects_pair"],
            "events": d["events_with_pairs"], "pairs": d["pairs"],
            "rate_pre_pp": d["rate_pre_pp"], "rate_post_obs_pp": d["rate_post_obs_pp"]}
    REP_OUT.write_text(json.dumps(REPORT, ensure_ascii=False, indent=1, default=str) + "\n",
                       encoding="utf-8")
    manifest = "".join(
        f"{sha(f)}  data/cal2026-08-28/{f.relative_to(CAL_DIR).as_posix()}\n"
        for f in sorted(CAL_DIR.rglob("*"))
        if f.is_file() and f.name != "MANIFEST.sha256")
    man_after = {l.split("  ", 1)[1]: l.split("  ", 1)[0]
                 for l in manifest.splitlines() if l.strip()}
    changed = {rel for rel, h in man_before.items() if man_after.get(rel) != h}
    if changed:
        for p in (LED_OUT, FIG_OUT, REP_OUT):      # a STOP freezes nothing
            p.unlink(missing_ok=True)
        stop(f"MANIFEST regeneration CHANGED {len(changed)} pre-existing entries "
             f"(e.g. {sorted(changed)[:3]}) — not a pure addition")
        return finish(root, ok=False)
    (CAL_DIR / "MANIFEST.sha256").write_text(manifest, encoding="utf-8")
    log(f"frozen {LED_OUT.name}, {FIG_OUT.name}, {REP_OUT.name}; MANIFEST "
        f"{len(man_before)} -> {len(man_after)} entries, pure addition asserted")
    for f in FIELDS:
        h = REPORT["headline"][f]
        log(f"  {f}: ate {h['ate_pp']} pp/yr (se {h['se_pair_pp']}), p {h['p_joint_effects_pair']}, "
            f"events {h['events']}, pairs {h['pairs']}, raw pre {h['rate_pre_pp']} -> "
            f"post_obs {h['rate_post_obs_pp']}")
    return finish(root, ok=True)


def finish(root: pathlib.Path, ok: bool) -> int:
    if not ok:
        REPORT["stops"] = STOPS
        p = root / "ledger_run_report_FAILED.json"
        p.write_text(json.dumps(REPORT, ensure_ascii=False, indent=1, default=str),
                     encoding="utf-8")
        log(f"{len(STOPS)} STOP condition(s) — NOTHING frozen. Report at {p}")
        return 1
    log("done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
